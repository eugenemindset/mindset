#!/usr/bin/env python3
"""Regenerate sw.js so the Home Screen app works offline.

The app pulls in roughly ninety files across four concepts, so the precache
list is generated from the working tree rather than kept by hand. The cache is
named after a hash of those files' contents: change any of them and the next
launch installs a fresh cache and drops the old one, which is what keeps a
cache-first service worker from ever serving something stale.

    python3 tools/build-sw.py
"""

import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Everything the app itself needs. `concepts/scratch-panel` is deliberately out:
# it is the older reference screen, it is not in the rotation, and it is the one
# page that loads webfonts from Google, which would never resolve offline.
TREES = ["app", "concepts/shared"]
CONCEPTS = [
    "concepts/first-screen-observations-typing",
    "concepts/first-screen-patterns-scratch",
    "concepts/first-screen-old-goal",
    "concepts/first-screen-emoji-swarm",
]

# Directory URLs the browser actually navigates to; the host maps these to the
# index.html inside, and a cache lookup for the file would miss.
DIRS = ["", "app/", "concepts/"] + [c + "/" for c in CONCEPTS]

SKIP = {".DS_Store"}


def collect():
    files = []
    for tree in TREES + CONCEPTS:
        base = ROOT / tree
        if not base.is_dir():
            sys.exit(f"missing {tree}")
        for path in sorted(base.rglob("*")):
            if path.is_file() and path.name not in SKIP:
                files.append(path.relative_to(ROOT).as_posix())
    files.append("concepts/index.html")
    files.append("index.html")
    return files


def version(files):
    digest = hashlib.sha256()
    for name in files:
        digest.update(name.encode())
        digest.update((ROOT / name).read_bytes())
    return digest.hexdigest()[:12]


def render(files):
    listed = DIRS + files
    body = "\n".join(f'  "{name}",' for name in listed)
    return f'''/* Generated by tools/build-sw.py — do not edit by hand. */

// Named after a hash of the precached contents, so a deploy always installs a
// new cache instead of reusing the old one.
const CACHE = "mindset-{version(files)}";

const FILES = [
{body}
];

self.addEventListener("install", (e) => {{
  e.waitUntil(
    caches
      .open(CACHE)
      // Individually rather than cache.addAll, which rejects the whole install
      // if a single file 404s and would leave the app with no offline copy.
      .then((cache) => Promise.all(FILES.map((f) => cache.add(scoped(f)).catch(() => {{}}))))
      .then(() => self.skipWaiting())
  );
}});

self.addEventListener("activate", (e) => {{
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
}});

// Cache first: the phone is often opened with no connection at all, and the
// hashed cache name means what we hold is never out of date.
self.addEventListener("fetch", (e) => {{
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    caches.match(req, {{ ignoreSearch: true }}).then(
      (hit) =>
        hit ||
        fetch(req)
          .then((res) => {{
            if (res.ok) {{
              const copy = res.clone();
              caches.open(CACHE).then((c) => c.put(req, copy));
            }}
            return res;
          }})
          .catch(() => hit)
    )
  );
}});

function scoped(path) {{
  return new Request(new URL(path, self.registration.scope), {{ cache: "reload" }});
}}
'''


def main():
    files = collect()
    out = ROOT / "sw.js"
    out.write_text(render(files))
    stamp = re.search(r'"mindset-(\w+)"', out.read_text()).group(1)
    print(f"sw.js: {len(files)} files, cache mindset-{stamp}")


if __name__ == "__main__":
    main()
